// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every other
// rankable pre-token protocol in the snapshot: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.03 x min(chains - 1, 5)            (multi-chain footprint, capped at 1.15)
//   velocity   = 1.10 when growth > 25 and age_days < 730, else 1.00 (young and fast-growing)
//   relative   = 1 + clamp(growth - category_median, -30, 60) / 100 x 0.3
//                (growth against the median of its own category's pre-token protocols)
//   implied    = max(1, round(base x growthMult x maturity x breadth x velocity x relative))
//
// TVL is the size of the prize, growth is its direction, age is how long the protocol has run with no
// token on record, chain count is how widely it is distributed, the velocity term is the early
// signal: a young protocol growing fast is the one the radar exists to catch before the crowd. The
// relative term compares a protocol with its own category: a lender growing while other lenders shrink
// is doing something its peers are not. The constants are the model's, stated in the dashboard. No
// protocol name is ever special-cased: the same function scores every row.

