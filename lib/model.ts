const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The median of a sorted list of numbers; null when the list is empty. */
export function median(values: number[]): number | null {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  if (sorted.length % 2 === 1) return sorted[mid]!;
  return (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/** Each category's median seven-day growth across the protocols given, keyed by category name. A
 *  category with too few protocols reporting growth gets no median: its protocols score a neutral 1. */
export function categoryMedians(protocols: SnapshotProtocol[]): Map<string, number> {
  const byCategory = new Map<string, number[]>();
  for (const p of protocols) {
    if (p.change_7d === null || !Number.isFinite(p.change_7d)) continue;
    const key = p.category ?? 'Other';
    const list = byCategory.get(key) ?? [];
    list.push(p.change_7d);
    byCategory.set(key, list);
  }
  const medians = new Map<string, number>();
  for (const [key, list] of byCategory) {
    if (list.length < MODEL.relative_min_count) continue;
    const m = median(list);
    if (m !== null) medians.set(key, m);
  }
  return medians;
}

/** The six multipliers and the implied value one protocol gets under `model`. `categoryMedian` is the
 *  median seven-day growth of the protocol's own category, or null when its category has none. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  model: ModelConstants,
  categoryMedian: number | null = null,
): { implied: number; growthPct: number; growthMult: number; maturityMult: number; breadthMult: number; velocityMult: number; relativeMult: number; age: number | null } {
  const age = ageDays(asOf, protocol.listed_at);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult = model.maturity_floor + (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const extraChains = Math.min(Math.max(protocol.chains.length - 1, 0), model.breadth_max_chains);
  const breadthMult = 1 + extraChains * model.breadth_step;
  const velocityMult = growthPct > model.velocity_threshold && ageForModel < model.velocity_age_days ? model.velocity_multiplier : 1;
  const relGrowth = categoryMedian === null ? 0 : Math.min(model.relative_cap, Math.max(model.relative_floor, growthPct - categoryMedian));
  const relativeMult = 1 + (relGrowth / 100) * model.relative_weight;
  const base = protocol.tvl_usd * model.base_multiple;
  const implied = Math.max(1, Math.round(base * growthMult * maturityMult * breadthMult * velocityMult * relativeMult));
  return { implied, growthPct, growthMult, maturityMult, breadthMult, velocityMult, relativeMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/** Wrapped, staked or bridged products of a token that already trades: not a launch of their own. */
const WRAPPED_WORD = /\b(wrapped|staked|staking)\b/i;
const EXCHANGE_PREFIX = /^(Binance|Coinbase|Bybit|Kraken|Bitget|OKX|Bitfinex|Gemini)\b/;
const EXCLUDED_CATEGORIES = new Set(['Bridge', 'Canonical Bridge', 'Liquid Staking', 'Liquid Restaking', 'Restaked BTC', 'CEX']);

/** Whether a protocol is one the board may rank: pre-token, not an exchange, not a versioned pool, and
 *  not a wrapped, staked or bridged product of a protocol whose token already trades. The watchlist's
 *  own rule, applied to every early row too: a staked-ETH product with a giant TVL is not a token
 *  launch waiting to happen, whatever its size. */
export function isRankable(p: SnapshotProtocol): boolean {
  return (
    isPreToken(p) &&
    !EXCLUDED_CATEGORIES.has(p.category ?? '') &&
    !VERSIONED.test(p.name) &&
    !WRAPPED_WORD.test(p.name) &&
    !EXCHANGE_PREFIX.test(p.name)
  );
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

