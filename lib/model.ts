/** The protocols the board ranks, strongest first, with ranks 1..n. */
export function buildBoard(snapshot: Snapshot, model: ModelConstants = MODEL): BoardRow[] {
  const index = bySlug(snapshot.protocols);
  const chosen = new Map<string, SnapshotProtocol>();
  // The watchlist is the floor: every slug, even one the snapshot no longer carries (it cannot, but the
  // board's coverage is the gate's row and is never gambled on a missing record).
  for (const slug of snapshot.watchlist) {
    const p = index.get(slug);
    if (p !== undefined) chosen.set(slug, p);
  }
  // The early radar: every other rankable pre-token protocol in the snapshot, whatever its TVL. The
  // floor is where the house's reading started, not where this radar stops: a small protocol growing
  // fast with no token on record is exactly the early find the board exists to surface.
  for (const p of snapshot.protocols) {
    if (!chosen.has(p.slug) && isRankable(p)) chosen.set(p.slug, p);
  }

  // The category medians come from the chosen set itself: each protocol is measured against the
  // peers the board actually ranks, so the relative term is the snapshot's own comparison.
  const medians = categoryMedians([...chosen.values()]);
  const scored = [...chosen.values()].map((p) => {
    const median = medians.get(p.category ?? 'Other') ?? null;
    const { implied, growthPct, growthMult, maturityMult, breadthMult, velocityMult, relativeMult, age } = impliedValue(p, snapshot.as_of, model, median);
    return { p, implied, growthPct, growthMult, maturityMult, breadthMult, velocityMult, relativeMult, age };
  });
  scored.sort((a, b) => b.implied - a.implied || (a.p.slug < b.p.slug ? -1 : a.p.slug > b.p.slug ? 1 : 0));
  return scored.map((s, i) => ({
    rank: i + 1,
    slug: s.p.slug,
    name: s.p.name,
    category: s.p.category,
    chains: s.p.chains,
    tvl_usd: s.p.tvl_usd,
    change_7d: s.p.change_7d,
    mcap_usd: s.p.mcap_usd,
    listed_at: s.p.listed_at,
    gecko_id: s.p.gecko_id,
    symbol: s.p.symbol,
    token_status: 'pre-token',
    age_days: s.age,
    implied_value_usd: s.implied,
    notes: protocolNotes(s.p, s.age, snapshot.watchlist.includes(s.p.slug)),
    model: {
      base_multiple: model.base_multiple,
      growth_pct: s.growthPct,
      growth_multiplier: round4(s.growthMult),
      maturity_multiplier: round4(s.maturityMult),
      breadth_multiplier: round4(s.breadthMult),
      velocity_multiplier: round4(s.velocityMult),
      relative_multiplier: round4(s.relativeMult),
      age_days: s.age,
    },
    farm_steps: farmSteps(s.p, s.age).map(stepText),
  }));
}

const round4 = (n: number): number => Math.round(n * 1e4) / 1e4;

/** A step as one string: its action, then its cost and time, within the gate's 20..600 characters. */
export function stepText(step: FarmStep): string {
  let s = `${step.text} Cost: ${step.cost}. Time: ${step.time}.`;
  if (s.length > 600) s = `${s.slice(0, 596)}...`;
  if (s.length < 20) s = `${s} Hold the position and check the protocol's own page.`;
  return s;
}

/** The first chain a protocol names, or a neutral phrase. */
function chainOf(p: SnapshotProtocol): string {
  return p.chains.length > 0 ? p.chains[0]! : 'its main chain';
}

/** How much capital one farm position needs, from the protocol's own TVL. */
function capitalFor(p: SnapshotProtocol): number {
  if (p.tvl_usd >= 5_000_000_000) return 250;
  if (p.tvl_usd >= 1_000_000_000) return 150;
  if (p.tvl_usd >= 100_000_000) return 100;
  return 50;
}

/** How long to hold, from the protocol's age: younger protocols get a longer qualifying window. */
function holdDaysFor(age: number | null): number {
  if (age === null) return 30;
  if (age < 180) return 60;
  if (age < 365) return 45;
  return 30;
}

/** The category's main action, in the words a farmer can follow. */
function actionFor(p: SnapshotProtocol, capital: number, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Supply $${capital} of USDC to ${name} on ${chain} and keep the position open.`;
  if (c.includes('dex') || c.includes('yield') || c.includes('leveraged farm') || c.includes('liquidity manager')) return `Provide $${capital} of liquidity to ${name}'s main pool on ${chain} and keep the position open.`;
  if (c.includes('bridge')) return `Bridge $${capital} of USDC to ${chain} through ${name} and use the bridged funds in its app.`;
  if (c.includes('staking') || c.includes('restak')) return `Stake $${capital} of the chain's staking asset through ${name} and keep the receipt.`;
  if (c.includes('perpetual') || c.includes('derivative') || c.includes('basis trading')) return `Deposit $${capital} of USDC as margin on ${name} and open one small hedge.`;
  if (c.includes('prediction')) return `Fund $${capital} and place one market position on ${name}.`;
  if (c.includes('curator') || c.includes('allocator') || c.includes('risk')) return `Deposit $${capital} into a ${name} vault on ${chain} and keep the shares.`;
  if (c.includes('stable')) return `Mint or deposit $${capital} of the stable asset through ${name} on ${chain}.`;
  if (c.includes('rwa')) return `Mint $${capital} of the protocol's yield asset on ${chain} and hold it.`;
  if (c.includes('insurance')) return `Buy $${capital} of cover from ${name} on ${chain} and keep the policy.`;
  if (c.includes('chain')) return `Bridge $${capital} of USDC to ${name}'s chain and use it in the chain's main app.`;
  if (c.includes('payment') || c.includes('card')) return `Load $${capital} onto ${name} on ${chain} and spend a small amount through it.`;
  return `Deposit $${capital} of USDC into ${name} on ${chain} and keep the position open.`;
}

/** The category's second qualifying action: a different touchpoint from the main deposit. */
function secondActionFor(p: SnapshotProtocol, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Borrow $20 against the deposit on ${name} and repay it the same week, so the position shows both sides.`;
  if (c.includes('dex') || c.includes('yield') || c.includes('leveraged farm') || c.includes('liquidity manager')) return `Swap $25 through ${name}'s main pool on ${chain} once, using the same wallet as the liquidity position.`;
  if (c.includes('bridge')) return `Bridge $25 back the other way through ${name} once, so the wallet shows a round trip.`;
  if (c.includes('staking') || c.includes('restak')) return `Claim or restake the staking rewards on ${name} once, so the wallet shows an active stake.`;
  if (c.includes('perpetual') || c.includes('derivative') || c.includes('basis trading')) return `Close the hedge on ${name} after two weeks and open a fresh one half the size.`;
  if (c.includes('prediction')) return `Settle one market on ${name} and place a second position in a different market.`;
  if (c.includes('curator') || c.includes('allocator') || c.includes('risk')) return `Deposit a further $25 into a second ${name} vault on ${chain} in the second month.`;
  if (c.includes('stable')) return `Swap $25 of the stable asset through ${name} on ${chain} once, from the same wallet.`;
  if (c.includes('rwa')) return `Reinvest the first yield payout from ${name} back into the same asset on ${chain}.`;
  if (c.includes('insurance')) return `Renew or top up the cover on ${name} once before the first policy ends.`;
  if (c.includes('chain')) return `Make one swap and one transfer on ${name}'s chain from the same wallet in the first month.`;
  if (c.includes('payment') || c.includes('card')) return `Make a second small spend through ${name} in a different week from the first.`;
  return `Make one extra on-chain action on ${name} on ${chain}, such as a swap or a vote, from the same wallet.`;
}

/**
 * A protocol's notes: short, plain-language readings of its own record, cautions and strengths.
 * Every note follows from the snapshot's figures (chains, growth, age, TVL, watchlist membership) and
 * names the figure it rests on, so a reader can check it. A protocol with nothing to flag gets one
 * neutral line.
 */
export function protocolNotes(p: SnapshotProtocol, age: number | null, watchlist: boolean = false): string[] {
  const notes: string[] = [];
  const chain = chainOf(p);
  if (watchlist) {
    notes.push(`On the house watchlist: at least $50M of TVL with no token on record.`);
  }
  if (p.chains.length === 1) {
    notes.push(`Runs on a single chain, ${chain}: a halt on that chain would freeze the whole position.`);
  } else if (p.chains.length >= 8) {
    notes.push(`Live on ${p.chains.length} chains: widely distributed, with more surfaces to watch.`);
  }
  if (p.change_7d !== null && p.change_7d < -10) {
    notes.push(`TVL fell ${Math.abs(p.change_7d).toFixed(2)}% in seven days: the position is shrinking, not growing.`);
  } else if (p.change_7d !== null && p.change_7d > 50) {
    notes.push(`Seven-day growth above 50%: momentum is real, and sharp rises can reverse just as fast.`);
  }
  if (age !== null && age < 90) {
    notes.push(`Listed under 90 days ago: a young protocol with a short record to judge it by.`);
  } else if (age !== null && age > 1095) {
    notes.push(`Running for over three years with no token on record: the wait itself is the story.`);
  }
  if (p.tvl_usd >= 1_000_000_000) {
    notes.push(`Over $1B of TVL: large enough that a token launch would be a major event.`);
  } else if (p.tvl_usd < 10_000_000) {
    notes.push(`Under $10M of TVL: small enough that a little growth moves it a lot, either way.`);
  }
  if (notes.length === 0) {
    notes.push(`A steady record: no single figure in the snapshot stands out, for better or worse.`);
  }
  return notes;
}

/**
 * A protocol's farm plan: seven steps, each an action with a cost and a time. The plan is derived from
 * the protocol's own record (category, chains, TVL, age), never from a hand-written list of names.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const action = actionFor(p, capital, chain);
  const second = secondActionFor(p, chain);
  return [
    {
      text: `Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.`,
      cost: 'under $3 of gas for the first transaction',
      time: '5 minutes',
    },
    {
      text: action,
      cost: `$${capital} of capital and about $${capital >= 150 ? 8 : 4} of gas`,
      time: '15 minutes to set up',
    },
    {
      text: second,
      cost: 'about $2 of gas',
      time: '10 minutes',
    },
    {
      text: `Make one qualifying action each week, such as a deposit, a borrow, a swap or a vote.`,
      cost: 'about $2 of gas a week',
      time: '10 minutes a week',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity is counted in more than one snapshot.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Before you withdraw, open the protocol's own points or rewards page and claim only from the link it publishes.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes',
    },
    {
      text: `Write the wallet, the dates and every transaction in a farm log, then unwind in two halves a week apart.`,
      cost: 'nothing but the log, plus about $4 of gas to exit',
      time: '5 minutes to log, 15 minutes to exit',
    },
  ];
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
    }));
}

